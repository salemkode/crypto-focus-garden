/**
 * Builds the page the iOS/Android WebView shows: the valley engine (three.js + garden) bundled
 * into one self-contained HTML string, written to src/components/valley/embed/html.generated.ts.
 *
 *   bun run build:valley          (writes the page)
 *   bun run check:valley          (fails if the page is out of date)
 *
 * Re-run after changing packages/garden or src/components/valley/{controller,protocol}.ts.
 */
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dir, '..');
const result = await Bun.build({ entrypoints: [join(root, 'src/components/valley/embed/entry.ts')], target: 'browser', format: 'iife', minify: true });
if (!result.success) { for (const log of result.logs) console.error(log); process.exit(1); }
const js = await result.outputs[0].text();

const html = `<!doctype html><html><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no, viewport-fit=cover">
<style>
html,body{margin:0;padding:0;width:100%;height:100%;overflow:hidden;background:transparent;
-webkit-user-select:none;user-select:none;-webkit-touch-callout:none;-webkit-tap-highlight-color:transparent;
touch-action:none;overscroll-behavior:none;-webkit-text-size-adjust:100%}
canvas{display:block;width:100%;height:100%;touch-action:none;outline:none}
</style></head><body><canvas id="valley"></canvas><script>${js.replace(/<\/script/gi, '<\\/script')}</script></body></html>`;

const hash = createHash('sha256').update(html).digest('hex').slice(0, 12);
const out = join(root, 'src/components/valley/embed/html.generated.ts');
if (process.argv.includes('--check')) {
  const current = existsSync(out) ? readFileSync(out, 'utf8').match(/VALLEY_HTML_HASH = '([0-9a-f]+)'/)?.[1] : null;
  if (current !== hash) { console.error(`valley embed is out of date (${current ?? 'missing'} != ${hash}); run: bun run build:valley`); process.exit(1); }
  console.log(`valley embed up to date (${hash})`);
  process.exit(0);
}
writeFileSync(out, `// Generated by scripts/build-valley-embed.mjs. Do not edit. Source hash ${hash}.\nexport const VALLEY_HTML_HASH = '${hash}';\nexport const VALLEY_HTML = ${JSON.stringify(html)};\n`);
console.log(`valley embed: ${(html.length / 1024).toFixed(0)} KB, hash ${hash} -> ${out}`);
