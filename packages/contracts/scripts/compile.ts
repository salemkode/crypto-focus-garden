import { compileString } from 'cashc';
import { readFile, writeFile, mkdir } from 'node:fs/promises';

const output = new URL('../artifacts/', import.meta.url);
await mkdir(output, { recursive: true });

for (const name of ['FocusForest', 'FocusDirectory']) {
  const source = await readFile(new URL(`../contracts/${name}.cash`, import.meta.url), 'utf8');
  const artifact = { ...compileString(source), updatedAt: '1970-01-01T00:00:00.000Z' };
  await writeFile(new URL(`${name}.artifact.ts`, output), `// Generated by bun run contracts:compile. Do not edit.\nexport default ${JSON.stringify(artifact, null, 2)} as const;\n`);
  console.log(`Compiled ${name} with ${artifact.compiler.name} ${artifact.compiler.version}`);
}
